// markdown renders early-close-backtest.md: every table of the -early-close
// run. The method and the conclusions are in docs/audit/pricing/early-close.md.
func (r *earlyCloseReport) markdown() string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("# Early close (Sell now) back-test and calibration\n\n")
	w("Generated by `server-go/cmd/calibrate -early-close` on %s. Machine-readable copy: `early-close-backtest.json`.\n", r.GeneratedAt)
	w("The formula, the method and the conclusions are in `early-close.md`; this file holds every table.\n\n")
	w("- Data: Binance BTCUSDT and ETHUSDT 1-second klines %s to %s (the live volatility estimator) and 1-minute\n", r.SecondFrom, r.DataTo)
	w("  klines %s to %s (proxy volatility: last 60 one-minute returns).\n", r.MinuteFrom, r.DataTo)
	w("- Valuation: `binary.QuoteEarlyClose` with `binary.EarlyCloseCorrection`, fee %.1f%%, P(win) clamped to [%.2f, %.2f],\n", r.FeePercent, r.MinProbability, r.MaxProbability)
	w("  cut-off %d s, stake %d minor units, payout = the engine's calm payout for the asset and expiry.\n", r.CutoffSeconds, r.StakeMinorUnits)
	w("- Periods: FIT = entries in the first %.0f%% of each window (regime cuts, the correction), TEST = the rest.\n", r.FitFraction*100)
	w("- Edge = payoff if held - value paid, percent of stake (positive: the platform pays less than the position is worth).\n")
	w("- Brier and log loss are for \"the position wins\" (a draw is not a win); a no-information P = 0.5 scores 0.25 and 0.6931.\n")
	w("- \"At the strike\": the current price within one tick of the entry (klines carry the last trade, which bounces\n")
	w("  between bid and ask, so a one-tick difference is usually no move of the mid the live engine prices on). These\n")
	w("  valuations form their own bin and are left out of the probability bins and of the fit.\n\n")

	w("## 1. Fitted correction (FIT period, per instrument, every expiry)\n\n")
	match := "no - update `models.DefaultEarlyCloseCalibration` / `DefaultEarlyCloseMinProbabilityPercent`"
	if r.DefaultMatchesFit {
		match = "yes"
	}
	w("Shipped defaults (`models.DefaultEarlyCloseCalibration`, `DefaultEarlyCloseMinProbabilityPercent`) equal this fit: **%s**.\n\n", match)
	b.WriteString("| Asset | seconds left up to | sigma / baseline up to | valuations | sigma scale | volatility floor (x baseline) | stickiness | log loss before | log loss after |\n|---|---|---|---|---|---|---|---|---|\n")
	for _, f := range r.Fit {
		for _, c := range f.Cells {
			w("| %s | %s | %s | %d | %g | %g | %g | %s | %s |\n", f.Symbol, bound(float64(c.MaxSecondsRemaining)), bound(c.MaxVolRatio), c.Samples,
				c.SigmaScale, c.MinVolRatio, c.Stickiness, prob(c.LogLossBefore), prob(c.LogLoss))
		}
	}
	w("\nLower clamp of P(win): positions the corrected model prices below each threshold (FIT period), and how they\n")
	w("ended. A clamp at t pays (1 - fee) x t of the full payout for them; it is safe while that stays below their win rate.\n")
	w("Lower clamp chosen: **%g%%** (the largest threshold safe in every band with at least %d positions).\n\n", r.RecommendedMinPercent, earlyCloseFloorMinSamples)
	b.WriteString("| Asset | seconds left up to | below (P, %) | positions | mean model P | win rate | draw rate |\n|---|---|---|---|---|---|---|\n")
	for _, f := range r.Fit {
		for _, ev := range f.Floor {
			w("| %s | %s | %g | %d | %s | %s | %s |\n", f.Symbol, bound(float64(ev.MaxSecondsRemaining)), ev.BelowPercent, ev.Samples,
				prob(ev.MeanPredicted), prob(ev.WinRate), prob(ev.DrawRate))
		}
	}
	w("\n")

	for vi, v := range r.Variants {
		w("## %d. Variant `%s`: %s\n\n", vi+2, v.Name, v.Description)
		r.summary(&b, v, "Live estimator, 1-second data", func(ins earlyCloseInstrument) []pricing.EarlyCloseBacktestResult { return ins.Live })
		if len(v.Rows) == 0 {
			r.summary(&b, v, "Proxy volatility, 1-minute data, two years", func(ins earlyCloseInstrument) []pricing.EarlyCloseBacktestResult { return ins.Proxy })
		}
		r.cells(&b, v, func(ins earlyCloseInstrument) []pricing.EarlyCloseBacktestResult { return ins.Live })
		r.reliability(&b, v, func(ins earlyCloseInstrument) []pricing.EarlyCloseBacktestResult { return ins.Live })
	}
	return b.String()
}

type pickFn func(ins earlyCloseInstrument) []pricing.EarlyCloseBacktestResult

func (r *earlyCloseReport) summary(b *strings.Builder, v earlyCloseVariant, title string, pick pickFn) {
	w := func(format string, args ...any) { fmt.Fprintf(b, format, args...) }
	w("### %s: summary (TEST period, every valuation time)\n\n", title)
	b.WriteString("| Asset | Expiry | Payout | Valued at (s left) | Entries fit / test | Refused | n | eff. n | Brier | Log loss | ECE | mean P | win rate | draw rate | value paid % | payoff % | edge % | +/- | edge before fee % | worst cell edge % | worst bin edge % | bins checked / negative / significantly negative |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")
	var checked, negative, significant int
	for _, ins := range v.Instruments {
		for _, res := range pick(ins) {
			c := res.Cell(pricing.ECPeriodTest, 0, pricing.ECRegimeAll)
			if c == nil {
				continue
			}
			checked, negative, significant = checked+res.BinsChecked, negative+res.BinsNegative, significant+res.BinsSignificantlyNegative
			w("| %s | %ds | %.1f%% | %s | %d / %d | %d of %d | %d | %.0f | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s (%s, +/- %s) | %s (%s, +/- %s) | %d / %d / %d |\n",
				res.Symbol, res.ExpirySeconds, res.PayoutPercent, joinInts(res.RemainingSeconds), res.FitEntries, res.TestEntries,
				res.Refused, res.Valuations, c.Samples, c.Effective, prob(c.Brier), prob(c.LogLoss), prob(c.ECE), prob(c.MeanPredicted),
				prob(c.WinRate), prob(c.DrawRate), pct(c.MeanValuePct), pct(c.MeanPayoffPct), pct(c.EdgePct), pct(c.EdgeHalfWidthPct),
				pct(c.EdgeBeforeFeePct), pct(res.WorstCellEdgePct), res.WorstCell, pct(res.WorstCellHalfWidth),
				pct(res.WorstBinEdgePct), res.WorstBin, pct(res.WorstBinHalfWidthPct),
				res.BinsChecked, res.BinsNegative, res.BinsSignificantlyNegative)
		}
	}
	w("\nReliability bins (TEST period, per valuation time and regime, at least 50 effective samples): %d checked, %d with a negative edge, %d significantly negative (edge + 95%% half-width < 0).\n\n",
		checked, negative, significant)
}

func (r *earlyCloseReport) cells(b *strings.Builder, v earlyCloseVariant, pick pickFn) {
	w := func(format string, args ...any) { fmt.Fprintf(b, format, args...) }
	w("### Live estimator: TEST period by valuation time and volatility regime\n\n")
	b.WriteString("| Asset | Expiry | s left | Regime | n | eff. n | Brier | Log loss | ECE | mean P | win rate | draw | edge % | +/- | before fee % |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")
	for _, ins := range v.Instruments {
		for _, res := range pick(ins) {
			for _, c := range res.Cells {
				if c.Period != pricing.ECPeriodTest {
					continue
				}
				rem := "all"
				if c.Remaining != 0 {
					rem = fmt.Sprint(c.Remaining)
				}
				w("| %s | %ds | %s | %s | %d | %.0f | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n",
					res.Symbol, res.ExpirySeconds, rem, c.Regime, c.Samples, c.Effective, prob(c.Brier), prob(c.LogLoss),
					prob(c.ECE), prob(c.MeanPredicted), prob(c.WinRate), prob(c.DrawRate), pct(c.EdgePct), pct(c.EdgeHalfWidthPct),
					pct(c.EdgeBeforeFeePct))
			}
		}
	}
	w("\n")
}

func (r *earlyCloseReport) reliability(b *strings.Builder, v earlyCloseVariant, pick pickFn) {
	w := func(format string, args ...any) { fmt.Fprintf(b, format, args...) }
	w("### Live estimator: reliability (TEST period, every valuation time, all regimes)\n\n")
	for _, ins := range v.Instruments {
		for _, res := range pick(ins) {
			c := res.Cell(pricing.ECPeriodTest, 0, pricing.ECRegimeAll)
			if c == nil {
				continue
			}
			w("**%s %ds** (regime cuts on sigma: %.3g / %.3g per sqrt s)\n\n", res.Symbol, res.ExpirySeconds, res.RegimeCuts[0], res.RegimeCuts[1])
			b.WriteString("| P(win) bin | n | eff. n | mean predicted | observed | +/- | draw rate | edge % | +/- |\n|---|---|---|---|---|---|---|---|---|\n")
			for _, bn := range c.Reliability {
				label := fmt.Sprintf("%.1f-%.1f", bn.PredLow, bn.PredHigh)
				if bn.AtStrike {
					label = "at the strike"
				}
				w("| %s | %d | %.0f | %s | %s | %s | %s | %s | %s |\n", label, bn.Count, bn.Effective,
					prob(bn.MeanPredicted), prob(bn.Observed), prob(bn.HalfWidth), prob(bn.DrawRate), pct(bn.EdgePct), pct(bn.EdgeHalfWidthPct))
			}
			w("\n")
		}
	}
}

func joinInts(xs []int64) string {
	parts := make([]string, len(xs))
	for i, x := range xs {
		parts[i] = fmt.Sprint(x)
	}
	return strings.Join(parts, ", ")
}
